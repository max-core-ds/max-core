#!/usr/bin/env node
//
// split-tree.mjs — make the big tree token-cheap to work with.
//
// Splits figma-tree.json into one file per top-level Figma page (CANVAS) under pages/,
// and emits a shallow catalog (catalog.json + INDEX.md) mapping each page to its
// COMPONENT / COMPONENT_SET masters, with node ids, clickable links, and Figma tier
// (derived from the "----- Atoms/Molecules/Organism -----" separator pages).
//
// Read INDEX.md — never a multi-MB page file. For a single subtree use query-tree.mjs.
//
// Usage: node split-tree.mjs [path/to/figma-tree.json]
//
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const treePath = process.argv[2] ?? join(here, 'figma-tree.json');
const pagesDir = join(here, 'pages');

const doc = JSON.parse(readFileSync(treePath, 'utf8'));

const slugify = (s) =>
  s
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'page';

const isSeparator = (name) => name.trim().startsWith('-----');
const tierOf = (name) => {
  const l = name.toLowerCase();
  if (l.includes('atom')) return 'Atoms';
  if (l.includes('molecul')) return 'Molecules';
  if (l.includes('organ')) return 'Organisms';
  return null;
};

const countNodes = (n) => 1 + (n.children ?? []).reduce((a, c) => a + countNodes(c), 0);

// COMPONENT / COMPONENT_SET masters, without descending into a set's variants.
const collectMasters = (n, depth, out, max = 5) => {
  for (const ch of n.children ?? []) {
    if (ch.type === 'COMPONENT_SET' || ch.type === 'COMPONENT') {
      out.push({ type: ch.type, name: ch.name, id: ch.id, link: ch.link });
      continue;
    }
    if (depth < max) collectMasters(ch, depth + 1, out, max);
  }
};

rmSync(pagesDir, { recursive: true, force: true });
mkdirSync(pagesDir, { recursive: true });

let tier = 'Foundations'; // pages before the first Atoms separator are foundations/docs
const catalog = [];
const usedSlugs = new Map();

for (const page of doc.children ?? []) {
  const name = page.name ?? '';
  if (isSeparator(name)) {
    const t = tierOf(name);
    if (t) tier = t;
    continue;
  }
  if (name.trim() === 'Cover') continue;

  let slug = slugify(name);
  const seen = usedSlugs.get(slug) ?? 0;
  usedSlugs.set(slug, seen + 1);
  if (seen) slug = `${slug}-${seen + 1}`;

  writeFileSync(join(pagesDir, `${slug}.json`), JSON.stringify(page, null, 2));

  const masters = [];
  collectMasters(page, 0, masters);
  const ids = new Set();
  const uniq = masters.filter((m) => !ids.has(m.id) && ids.add(m.id));

  catalog.push({
    page: name,
    slug,
    tier,
    nodeId: page.id,
    link: page.link,
    nodes: countNodes(page),
    masters: uniq,
  });
}

writeFileSync(join(here, 'catalog.json'), `${JSON.stringify(catalog, null, 2)}\n`);

// INDEX.md — the always-readable map.
const out = [];
out.push('# Figma tree index');
out.push('');
out.push(
  `Generated by \`split-tree.mjs\` from \`figma-tree.json\` — ${catalog.length} pages. ` +
    'Read this file, not the multi-MB `pages/*.json`.',
);
out.push('');
out.push('For a component subtree: `node query-tree.mjs "<name|nodeId>" [depth]`.');
out.push('Regenerate the tree with `./fetch-tree.sh`, then rerun `node split-tree.mjs`.');
out.push('');
let curTier;
for (const p of catalog) {
  if (p.tier !== curTier) {
    curTier = p.tier;
    out.push(`## ${curTier ?? 'Ungrouped'}`);
    out.push('');
  }
  out.push(`### ${p.page}`);
  out.push(`\`${p.nodeId}\` · ${p.nodes} nodes · \`pages/${p.slug}.json\``);
  if (p.masters.length) {
    for (const m of p.masters) {
      const tag = m.type === 'COMPONENT_SET' ? 'SET' : 'cmp';
      out.push(`- \`[${tag}]\` **${m.name}** — \`${m.id}\` · [open](${m.link})`);
    }
  } else {
    out.push('- _(no component masters)_');
  }
  out.push('');
}
writeFileSync(join(here, 'INDEX.md'), `${out.join('\n')}`);

console.log(`Split ${catalog.length} pages → pages/`);
console.log('Wrote catalog.json and INDEX.md');
